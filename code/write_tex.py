"""Turns results/results.json into paper/results.tex (\\setres{key}{value}).
The best value in every table column is set in bold automatically.
Missing entries stay as red '--' placeholders in the PDF."""
import argparse, json, os

p = argparse.ArgumentParser()
p.add_argument("--out", default="results")
p.add_argument("--tex", default="../results.tex")
a = p.parse_args()
R = json.load(open(os.path.join(a.out, "results.json")))
lines = ["% auto-generated by code/write_tex.py -- do not edit by hand"]


def put(key, val, bold=False):
    s = f"{val:.2f}"
    lines.append("\\setres{" + key + "-raw}{" + s + "}")
    if bold:
        s = "\\textbf{" + s + "}"
    lines.append("\\setres{" + key + "}{" + s + "}")


def column(entries):
    """entries: list of (key, value or None); bolds the maximum."""
    vals = [v for _, v in entries if v is not None]
    best = max(vals) if vals else None
    for k, v in entries:
        if v is not None:
            put(k, v, v == best)


def g(d, *path):
    for q in path:
        if not isinstance(d, dict) or q not in d:
            return None
        d = d[q]
    return d


MAIN = ["resnet", "vit", "zsname", "zssape", "genvlm", "lp", "clipad", "tipf", "sava"]
for dom in ("pv", "pd"):
    for met in ("acc", "f1"):
        column([(f"{m}-{dom}-{met}", g(R, m, dom, met)) for m in MAIN])

FS = ["lp", "clipad", "tipf", "sava"]
for k in map(str, R.get("meta", {}).get("shots", [1, 2, 4, 8, 16])):
    for dom, tag in (("pv", "fs"), ("pd", "fspd")):
        column([(f"{tag}-{m}-{k}", g(R, "fewshot", k, m, dom, "acc")) for m in FS])
        for m in FS:
            sd = g(R, "fewshot", k, m + "_std", dom, "acc")
            if sd is not None:
                put(f"{tag}sd-{m}-{k}", sd)

for dom in ("pv", "pd"):
    for met in ("acc", "f1"):
        column([(f"abl-{x}-{dom}-{met}", g(R, "ablation", x, dom, met)) for x in "abcdefg"])

# trainable parameters (millions)
P = R.get("params", {})
for k in ("resnet", "vit", "clipad", "tipf", "sava"):
    if k in P:
        lines.append(f"\\setres{{par-{k}}}{{{P[k] / 1e6:.2f}M}}")
if "sava_16shot" in P:
    lines.append(f"\\setres{{par-sava16}}{{{P['sava_16shot'] / 1e6:.2f}M}}")

# derived numbers quoted in the text
def diff(key, x, y):
    if x is not None and y is not None:
        lines.append(f"\\setres{{{key}}}{{{x - y:+.2f}}}")

diff("gain-sape-pv", g(R, "zssape", "pv", "acc"), g(R, "zsname", "pv", "acc"))
diff("gain-sape-pd", g(R, "zssape", "pd", "acc"), g(R, "zsname", "pd", "acc"))
diff("gain-pd-vit", g(R, "sava", "pd", "acc"), g(R, "vit", "pd", "acc"))
diff("gain-pd-resnet", g(R, "sava", "pd", "acc"), g(R, "resnet", "pd", "acc"))
diff("gain-1shot-tipf", g(R, "fewshot", "1", "sava", "pv", "acc"), g(R, "fewshot", "1", "tipf", "pv", "acc"))
diff("gain-16shot-tipf-pd", g(R, "fewshot", "16", "sava", "pd", "acc"), g(R, "fewshot", "16", "tipf", "pd", "acc"))
diff("gain-crop", g(R, "ablation", "e", "pd", "acc"), g(R, "ablation", "d", "pd", "acc"))
diff("gain-reg", g(R, "ablation", "f", "pd", "acc"), g(R, "ablation", "e", "pd", "acc"))
diff("drop-pv-pd", g(R, "sava", "pd", "acc"), g(R, "sava", "pv", "acc"))
m = R.get("meta", {})
for k in ("n_train", "n_val", "n_test", "n_pd"):
    if k in m:
        lines.append(f"\\setres{{{k}}}{{{m[k]:,}}}")
if "genvlm" in R and "n_pv" in R["genvlm"]:
    lines.append(f"\\setres{{n-genvlm}}{{{R['genvlm']['n_pv']:,}}}")

open(a.tex, "w").write("\n".join(lines) + "\n")
print(f"wrote {len(lines) - 1} values to {a.tex}")
